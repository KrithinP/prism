"""Certify PRISM's evaluator against the pinned MLPD KAIST implementation.

This is a fail-closed differential test, not an informational demo. It:

1. verifies the pinned evaluator/annotation/detection file hashes;
2. runs all five released detection files through the pinned evaluator;
3. re-scores the same files with ``prism.eval.canonical``;
4. checks the pinned output against the released table (display precision);
5. checks local-vs-pinned All/Day/Night within 0.1 MR point; and
6. persists commands, stdout, stderr, hashes, values and verdicts.

The historical evaluator may fail while drawing its figure under new
matplotlib versions *after* printing all three metrics. A nonzero return code
is therefore recorded but accepted only when all metric rows were parsed.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import re
import shlex
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path

import numpy as np

from prism.eval.canonical import evaluate_reference
from prism.provenance import atomic_write_json

EVAL_DIR = Path("external/MLPD-eval/evaluation_script")
PIN_MANIFEST = Path("external/evaluator_manifest.json")
DEFAULT_FILES = (
    "MLPD_result.txt",
    "ARCNN_result.txt",
    "MBNet_result.txt",
    "CIAN_result.txt",
    "MSDS-RCNN_result.txt",
)
PUBLISHED_NAME = {
    "MLPD_result.txt": "MLPD-VGG16",
    "ARCNN_result.txt": "AR-CNN",
    "MBNet_result.txt": "MBNet",
    "CIAN_result.txt": "CIAN",
    "MSDS-RCNN_result.txt": "MSDS-RCNN",
}
LOCAL_TOLERANCE_MR_POINTS = 0.1
DISPLAY_TOLERANCE_MR_POINTS = 0.011


def sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def parse_mlpd_output(stdout: str) -> dict[str, float]:
    rows: dict[str, float] = {}
    for line in stdout.splitlines():
        match = re.match(r"\s*MR_(all|day|night):\s+([0-9.]+)\s*$", line)
        if match:
            rows[match.group(1)] = float(match.group(2))
    return rows


def verify_pinned_files(manifest_path: Path) -> dict:
    if not manifest_path.exists():
        raise FileNotFoundError(f"{manifest_path} is missing; run scripts/pin_mlpd_eval.py --clone")
    manifest = json.loads(manifest_path.read_text())
    failures = []
    checked = {}
    for rel, expected in manifest.get("files", {}).items():
        # Generated bytecode is not evaluator source and can legitimately
        # change with the interpreter version.
        if "__pycache__" in rel or rel.endswith(".pyc"):
            continue
        path = Path("external/MLPD-eval") / Path(rel)
        if not path.exists():
            failures.append(f"missing: {path}")
            continue
        actual = sha256_file(path)
        checked[rel] = actual
        if actual != expected:
            failures.append(f"hash mismatch: {path}")
    if failures:
        raise RuntimeError("pinned evaluator integrity failure:\n  " + "\n  ".join(failures))
    return {
        "commit_sha": manifest["commit_sha"],
        "files": checked,
        "published": manifest["bundled_reference_results"],
    }


def run_mlpd(ann: Path, det_txt: Path, fig: Path) -> dict:
    env = dict(os.environ, MPLBACKEND="Agg")
    cmd = [
        sys.executable,
        "evaluation_script.py",
        "--annFile",
        str(ann.resolve()),
        "--rstFiles",
        str(det_txt.resolve()),
        "--evalFig",
        str(fig.resolve()),
    ]
    proc = subprocess.run(cmd, cwd=EVAL_DIR, capture_output=True, text=True, env=env, check=False)
    return {
        "command": shlex.join(cmd),
        "returncode": proc.returncode,
        "stdout": proc.stdout,
        "stderr": proc.stderr,
        "metrics": parse_mlpd_output(proc.stdout),
    }


def load_detections(det_txt: Path) -> dict[int, list[tuple[float, ...]]]:
    out: dict[int, list[tuple[float, ...]]] = {}
    for line in det_txt.read_text().splitlines():
        if not line.strip():
            continue
        image_id, x, y, width, height, score = map(float, line.split(","))
        out.setdefault(int(image_id) - 1, []).append((x, y, width, height, score))
    return out


def canonical_mr_for_file(det_txt: Path, ann: Path) -> dict[str, float | None]:
    detections = load_detections(det_txt)
    data = json.loads(ann.read_text())
    ids = sorted(int(image["id"]) for image in data["images"])
    day_ids = set(ids[:1455])
    by_image: dict[int, list[dict]] = {}
    for annotation in data["annotations"]:
        by_image.setdefault(int(annotation["image_id"]), []).append(annotation)

    frames = []
    for image in sorted(data["images"], key=lambda item: int(item["id"])):
        image_id = int(image["id"])
        rows = detections.get(image_id, [])
        boxes = np.asarray([row[:4] for row in rows], np.float32).reshape(-1, 4)
        scores = np.asarray([row[4] for row in rows], np.float32)
        if len(boxes):
            boxes[:, 2] += boxes[:, 0]
            boxes[:, 3] += boxes[:, 1]
        gt_boxes, gt_classes, gt_occlusion = [], [], []
        for gt in by_image.get(image_id, []):
            x, y, width, height = gt["bbox"]
            gt_boxes.append([x, y, x + width, y + height])
            is_person = gt["category_id"] == 1 and not gt.get("ignore", 0)
            gt_classes.append(1 if is_person else 0)
            gt_occlusion.append(gt.get("occlusion", 0))
        frames.append(
            {
                "id": image_id,
                "det_boxes": boxes,
                "det_scores": scores,
                "gt_boxes": np.asarray(gt_boxes, np.float32).reshape(-1, 4),
                "gt_classes": np.asarray(gt_classes, np.int64),
                "gt_occlusion": np.asarray(gt_occlusion, np.int64),
                "is_day": image_id in day_ids,
            }
        )
    return evaluate_reference(frames, require_reachable=False)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--ann", default=str(EVAL_DIR / "KAIST_annotation.json"))
    parser.add_argument(
        "--det-txts",
        nargs="*",
        default=None,
        help="custom released-format files; default certifies all five bundled files",
    )
    parser.add_argument(
        "--out-dir",
        default="outputs/evaluator_parity",
        help="certificate, raw stdout/stderr, and figures",
    )
    args = parser.parse_args()

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    ann = Path(args.ann)
    if not ann.exists():
        raise SystemExit(f"annotation JSON not found: {ann}; run scripts/pin_mlpd_eval.py --clone")

    try:
        pin = verify_pinned_files(PIN_MANIFEST)
    except (OSError, ValueError, RuntimeError, KeyError) as error:
        raise SystemExit(str(error)) from error

    paths = (
        [Path(path) for path in args.det_txts]
        if args.det_txts is not None
        else [EVAL_DIR / "state_of_arts" / name for name in DEFAULT_FILES]
    )
    report = {
        "schema_version": 1,
        "created_at": datetime.now(UTC).isoformat(),
        "passed": True,
        "thresholds_mr_points": {
            "local_vs_pinned": LOCAL_TOLERANCE_MR_POINTS,
            "pinned_vs_published_display": DISPLAY_TOLERANCE_MR_POINTS,
        },
        "evaluator_commit": pin["commit_sha"],
        "evaluator_manifest_sha256": sha256_file(PIN_MANIFEST),
        "annotation": {"path": str(ann), "sha256": sha256_file(ann)},
        "files": [],
    }

    for det_txt in paths:
        item = {"path": str(det_txt), "exists": det_txt.exists(), "passed": True}
        if not det_txt.exists():
            item.update({"passed": False, "error": "missing detection file"})
            report["passed"] = False
            report["files"].append(item)
            continue

        stem = det_txt.stem
        reference = run_mlpd(ann, det_txt, out_dir / f"{stem}.jpg")
        (out_dir / f"{stem}.stdout.txt").write_text(reference["stdout"])
        (out_dir / f"{stem}.stderr.txt").write_text(reference["stderr"])
        ours = canonical_mr_for_file(det_txt, ann)
        item.update(
            {
                "sha256": sha256_file(det_txt),
                "reference_command": reference["command"],
                "reference_returncode": reference["returncode"],
                "pinned_mr_points": reference["metrics"],
                "local_mr_points": {
                    key: (None if ours[key] is None else ours[key] * 100)
                    for key in ("all", "day", "night")
                },
                "deltas_local_vs_pinned": {},
                "deltas_pinned_vs_published": {},
            }
        )

        if set(reference["metrics"]) != {"all", "day", "night"}:
            item["passed"] = False
            item["error"] = "failed to parse all three reference rows"
        else:
            for key in ("all", "day", "night"):
                delta = abs(reference["metrics"][key] - item["local_mr_points"][key])
                item["deltas_local_vs_pinned"][key] = delta
                if delta > LOCAL_TOLERANCE_MR_POINTS:
                    item["passed"] = False

        published_name = PUBLISHED_NAME.get(det_txt.name)
        if published_name:
            values = pin["published"][published_name]
            for key, expected in zip(("all", "day", "night"), values, strict=True):
                actual = reference["metrics"].get(key)
                delta = None if actual is None else abs(actual - expected)
                item["deltas_pinned_vs_published"][key] = delta
                if delta is None or delta > DISPLAY_TOLERANCE_MR_POINTS:
                    item["passed"] = False

        report["passed"] = report["passed"] and item["passed"]
        report["files"].append(item)

    report_path = out_dir / "parity_report.json"
    atomic_write_json(report_path, report)
    for item in report["files"]:
        print(f"{Path(item['path']).name:<24} {'PASS' if item['passed'] else 'FAIL'}")
        if item.get("pinned_mr_points"):
            print(f"  pinned: {item['pinned_mr_points']}")
            print(f"  local : {item['local_mr_points']}")
    print(f"\ncertificate: {report_path}")
    if not report["passed"]:
        raise SystemExit("evaluator parity certification FAILED")


if __name__ == "__main__":
    main()
